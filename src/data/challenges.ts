// ─── Types ────────────────────────────────────────────────

export type ChallengeCategory =
  | 'dopamine_reset'
  | 'attention_restoration'
  | 'prefrontal'
  | 'social'
  | 'sleep_circadian'
  | 'boredom_tolerance'
  | 'creative_flow';

// ─── Verification Types ──────────────────────────────────

export type VerificationType =
  | 'background_timer'    // phone-free walk/activity (AppState detection)
  | 'photo_proof'         // take a photo of the result
  | 'reflection_gate'     // write 50+ char response
  | 'screen_time_api'     // Future: falls back to honor_system
  | 'honor_system';       // simple "I did it" toggle

export interface DifficultyTier {
  description: string;
  duration: string;
  timerSeconds?: number;    // for background_timer verification
  minCharacters?: number;   // for reflection_gate verification
}

export interface Challenge {
  day: number;
  title: string;
  description: string;      // default/medium description (backward compat)
  category: ChallengeCategory;
  phase: 1 | 2 | 3 | 4;
  duration: string;          // default/medium duration (backward compat)
  difficulty: 1 | 2 | 3 | 4 | 5;
  scienceBite: string;
  studyRef: string;
  notificationTitle: string;
  notificationBody: string;
  completionPrompt: string;
  emoji: string;

  // V2 fields (optional for backward compatibility with existing data)
  verificationType?: VerificationType;
  easy?: DifficultyTier;
  medium?: DifficultyTier;
  hard?: DifficultyTier;

  // Legacy fields (kept for backward compat, will be removed)
  requiresSession: boolean;
  sessionMinDuration?: number;
  sessionMinProtection: 'easy' | 'strict' | 'ruthless';
}


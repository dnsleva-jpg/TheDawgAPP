// ─── Helper Functions ────────────────────────────────────

/**
 * Get the verification type for a challenge.
 * Falls back to inferring from legacy fields if V2 field not set.
 */
export function getChallengeVerificationType(challenge: Challenge): VerificationType {
  if (challenge.verificationType) return challenge.verificationType;

  // Infer from legacy fields
  if (challenge.requiresSession) return 'background_timer';

  // Infer from category
  switch (challenge.category) {
    case 'creative_flow': return 'photo_proof';
    case 'sleep_circadian': return 'honor_system';
    case 'social': return 'honor_system';
    default: return 'honor_system';
  }
}

/**
 * Get challenge description for a specific difficulty tier.
 */
export function getChallengeForDifficulty(
  challenge: Challenge,
  difficulty: 'easy' | 'medium' | 'hard'
): { description: string; duration: string; timerSeconds?: number; minCharacters?: number } {
  const tier = challenge[difficulty];
  if (tier) return tier;

  // Fallback to default description
  return {
    description: challenge.description,
    duration: challenge.duration,
    timerSeconds: challenge.sessionMinDuration,
  };
}

